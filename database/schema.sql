CREATE TABLE users (
    user_id        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    first_name     VARCHAR(50) NOT NULL,
    last_name      VARCHAR(50) NOT NULL,
    email          VARCHAR(100) NOT NULL,
    password_hash  VARCHAR(255) NOT NULL,
    university     VARCHAR(100),
    major          VARCHAR(100),
    avatar_url     VARCHAR(255),
    role           VARCHAR(10) NOT NULL DEFAULT 'student',
    is_blocked     BOOLEAN NOT NULL DEFAULT FALSE,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_users PRIMARY KEY (user_id),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_role
        CHECK (role IN ('student', 'admin')),
    CONSTRAINT ck_users_email_format
        CHECK (email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
    CONSTRAINT ck_users_names_filled
        CHECK (length(btrim(first_name)) > 0
        AND length(btrim(last_name)) > 0)
);

CREATE TABLE skills (
    skill_id    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    skill_name  VARCHAR(50) NOT NULL,
    category    VARCHAR(50) NOT NULL DEFAULT 'General',

    CONSTRAINT pk_skills PRIMARY KEY (skill_id),
    CONSTRAINT uq_skills_name UNIQUE (skill_name),
    CONSTRAINT ck_skills_name_filled
        CHECK (length(btrim(skill_name)) > 0)
);
-- 3. USER_SKILLS
CREATE TABLE user_skills (
    user_id INTEGER NOT NULL,
    skill_id INTEGER NOT NULL,

    CONSTRAINT pk_user_skills PRIMARY KEY (user_id, skill_id),
    CONSTRAINT fk_user_skills_user
        FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_user_skills_skill
        FOREIGN KEY (skill_id)
        REFERENCES skills (skill_id) ON DELETE CASCADE
);

-- 4. PROJECTS
CREATE TABLE projects (
    project_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    captain_id INTEGER NOT NULL,
    title VARCHAR(150) NOT NULL,
    description TEXT NOT NULL,
    link VARCHAR(255),
    status VARCHAR(20) NOT NULL DEFAULT 'looking_for_team',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_projects PRIMARY KEY (project_id),
    CONSTRAINT fk_projects_captain
        FOREIGN KEY (captain_id)
        REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT ck_projects_status
        CHECK (status IN ('looking_for_team', 'in_progress', 'done')),
    CONSTRAINT ck_projects_link
        CHECK (link IS NULL OR link ~* '^https?://'),
    CONSTRAINT ck_projects_title_filled
        CHECK (length(btrim(title)) > 0),
    CONSTRAINT ck_projects_dates
        CHECK (updated_at >= created_at)
);

-- 5. PROJECT_SKILLS
CREATE TABLE project_skills (
    project_id INTEGER NOT NULL,
    skill_id INTEGER NOT NULL,
    skill_type VARCHAR(4) NOT NULL,

    CONSTRAINT pk_project_skills PRIMARY KEY (project_id, skill_id),
    CONSTRAINT fk_project_skills_proj
        FOREIGN KEY (project_id)
        REFERENCES projects (project_id) ON DELETE CASCADE,
    CONSTRAINT fk_project_skills_skill
        FOREIGN KEY (skill_id)
        REFERENCES skills (skill_id) ON DELETE CASCADE,
    CONSTRAINT ck_project_skills_type
        CHECK (skill_type IN ('have', 'need'))
);
-- 6. PROJECT_MEMBERS
CREATE TABLE project_members (
    project_id INTEGER NOT NULL,
    user_id INTEGER NOT NULL,
    member_role VARCHAR(50) NOT NULL DEFAULT 'member',
    joined_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_project_members PRIMARY KEY (project_id, user_id),
    CONSTRAINT fk_project_members_proj
        FOREIGN KEY (project_id)
        REFERENCES projects (project_id) ON DELETE CASCADE,
    CONSTRAINT fk_project_members_user
        FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON DELETE CASCADE
);

-- 7. CONNECTIONS
CREATE TABLE connections (
    connection_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    sender_id INTEGER NOT NULL,
    receiver_id INTEGER NOT NULL,
    project_id INTEGER,
    message VARCHAR(500),
    status VARCHAR(10) NOT NULL DEFAULT 'pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    responded_at TIMESTAMPTZ,

    CONSTRAINT pk_connections PRIMARY KEY (connection_id),
    CONSTRAINT fk_connections_sender
        FOREIGN KEY (sender_id)
        REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_connections_receiver
        FOREIGN KEY (receiver_id)
        REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_connections_project
        FOREIGN KEY (project_id)
        REFERENCES projects (project_id) ON DELETE SET NULL,
    CONSTRAINT ck_connections_not_self
        CHECK (sender_id <> receiver_id),
    CONSTRAINT ck_connections_status
        CHECK (status IN ('pending', 'accepted', 'rejected')),
    CONSTRAINT ck_connections_responded
        CHECK ((status = 'pending') = (responded_at IS NULL)),
    CONSTRAINT ck_connections_dates
        CHECK (responded_at IS NULL OR responded_at >= created_at)
);

-- 8. RATINGS
CREATE TABLE ratings (
    rating_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    rater_id INTEGER NOT NULL,
    rated_user_id INTEGER NOT NULL,
    project_id INTEGER NOT NULL,
    overall_stars SMALLINT NOT NULL,
    communication SMALLINT NOT NULL,
    punctuality SMALLINT NOT NULL,
    technical_skill SMALLINT NOT NULL,
    teamwork SMALLINT NOT NULL,
    comment TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_ratings PRIMARY KEY (rating_id),
    CONSTRAINT fk_ratings_rater
        FOREIGN KEY (rater_id)
        REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_ratings_rated
        FOREIGN KEY (rated_user_id)
        REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_ratings_project
        FOREIGN KEY (project_id)
        REFERENCES projects (project_id) ON DELETE CASCADE,
    CONSTRAINT uq_ratings_once
        UNIQUE (rater_id, rated_user_id, project_id),
    CONSTRAINT ck_ratings_not_self
        CHECK (rater_id <> rated_user_id),
    CONSTRAINT ck_ratings_overall CHECK (overall_stars BETWEEN 1 AND 5),
    CONSTRAINT ck_ratings_comm CHECK (communication BETWEEN 1 AND 5),
    CONSTRAINT ck_ratings_punct CHECK (punctuality BETWEEN 1 AND 5),
    CONSTRAINT ck_ratings_tech CHECK (technical_skill BETWEEN 1 AND 5),
    CONSTRAINT ck_ratings_team CHECK (teamwork BETWEEN 1 AND 5),
    CONSTRAINT ck_ratings_comment CHECK (length(btrim(comment)) > 0)
);
-- 9. PROJECT_REVIEWS
CREATE TABLE project_reviews (
    review_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    project_id INTEGER NOT NULL,
    reviewer_id INTEGER NOT NULL,
    stars SMALLINT NOT NULL,
    comment TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_project_reviews PRIMARY KEY (review_id),
    CONSTRAINT fk_project_reviews_proj
        FOREIGN KEY (project_id)
        REFERENCES projects (project_id) ON DELETE CASCADE,
    CONSTRAINT fk_project_reviews_user
        FOREIGN KEY (reviewer_id)
        REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT uq_project_reviews_once
        UNIQUE (project_id, reviewer_id),
    CONSTRAINT ck_project_reviews_stars
        CHECK (stars BETWEEN 1 AND 5)
);

-- 10. NOTIFICATIONS
